static bool term_font_5x7_get_glyph_dsc(const lv_font_t *font, lv_font_glyph_dsc_t *dsc_out,
                                        uint32_t unicode_letter, uint32_t unicode_letter_next)
{
    (void)font;
    (void)unicode_letter_next;

    if (unicode_letter == '\t') {
        unicode_letter = ' ';
    }
    if (unicode_letter < 0x20 || unicode_letter > 0x7E) {
        return false;
    }

    dsc_out->adv_w = 5;   // 4px glyph + 1px spacing = 5px horizontal advance (63 cols in 315px)
    dsc_out->box_w = 8;   // 1 byte (8 bits) per row so row stride is byte-aligned
    dsc_out->box_h = 7;   // 7 rows high (34 rows in 238px)
    dsc_out->ofs_x = 0;
    dsc_out->ofs_y = 0;
    dsc_out->bpp   = 1;
    dsc_out->is_placeholder = false;
    return true;
}

static const uint8_t *term_font_5x7_get_glyph_bitmap(const lv_font_t *font, uint32_t unicode_letter)
{
    (void)font;
    if (unicode_letter == '\t') {
        unicode_letter = ' ';
    }
    if (unicode_letter < 0x20 || unicode_letter > 0x7E) {
        return s_font_5x7_bitmaps[0];
    }
    return s_font_5x7_bitmaps[unicode_letter - 0x20];
}

